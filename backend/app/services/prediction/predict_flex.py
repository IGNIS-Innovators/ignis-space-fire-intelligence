"""
IGNIS — Space Fire Intelligence
Module: backend.app.services.prediction.predict_flex

Reusable Prediction Inference Service for FLEX Droplet Burning Rate Constant K.
Consumes pre-ignition chamber and droplet parameters, validates thermodynamic bounds,
detects out-of-distribution extrapolation risks, and produces standardized predictions.
"""

from pathlib import Path
from typing import Any, Dict, List, Optional
import joblib
import numpy as np
import pandas as pd

from backend.app.core.config import settings

SUPPORTED_FUELS = {"Methanol", "Heptane"}

SCIENTIFIC_DISCLAIMER = (
    "EXPERIMENTAL RESEARCH PROTOTYPE: This prediction is generated by a statistical regression model "
    "trained on historical NASA PSI-69 FLEX microgravity droplet data. It estimates the quasi-steady droplet "
    "burning rate constant K (mm²/s) in quiescent microgravity. It DOES NOT provide certified spacecraft fire "
    "safety ratings, ignition probability estimates, or structural flammability clearance for human spaceflight missions."
)


class FlexPredictionService:
    """
    Inference service for predicting the droplet burning rate constant K (mm²/s)
    based on verified NASA PSI-69 pre-ignition experimental conditions.
    """

    def __init__(
        self,
        models_dir: Optional[Path] = None,
        model_path: Optional[Path] = None,
        metadata_path: Optional[Path] = None,
    ):
        if model_path is not None:
            self.models_dir = Path(model_path).parent
        else:
            self.models_dir = models_dir or settings.MODELS_DIR
        self._rf_pipeline = None
        self._ridge_pipeline = None
        self._metadata = None
        self._load_artifacts()

    def _load_artifacts(self) -> None:
        """Loads both Ridge and Random Forest pipelines and metadata from models directory."""
        rf_path = self.models_dir / "flex_burning_rate_rf.joblib"
        ridge_path = self.models_dir / "flex_burning_rate_ridge.joblib"
        meta_path = self.models_dir / "flex_model_metadata.joblib"

        if rf_path.exists():
            rf_obj = joblib.load(rf_path)
            self._rf_pipeline = rf_obj["pipeline"] if isinstance(rf_obj, dict) and "pipeline" in rf_obj else rf_obj

        if ridge_path.exists():
            ridge_obj = joblib.load(ridge_path)
            self._ridge_pipeline = ridge_obj["pipeline"] if isinstance(ridge_obj, dict) and "pipeline" in ridge_obj else ridge_obj

        if meta_path.exists():
            self._metadata = joblib.load(meta_path)
        else:
            self._metadata = {}

    def is_ready(self) -> bool:
        """Returns True if at least one trained pipeline is loaded."""
        return self._ridge_pipeline is not None or self._rf_pipeline is not None

    def get_default_model_name(self) -> str:
        return "Ridge Regression (Tuned)"

    def predict(
        self,
        fuel: str,
        ambient_pressure_kpa: float,
        o2_mole_fraction: float,
        n2_mole_fraction: float,
        co2_mole_fraction: float,
        he_mole_fraction: float,
        droplet_initial_diameter_mm: float,
        model_choice: str = "ridge",
    ) -> Dict[str, Any]:
        """
        Predicts the quasi-steady droplet burning rate constant K (mm²/s).
        """
        # 1. Check artifact readiness
        if not self.is_ready():
            raise FileNotFoundError(
                "Model artifacts missing. Deployed model requires training artifacts in 'models/'. "
                "Execute 'python backend/app/services/prediction/train_flex.py' to generate them."
            )

        # 2. Validation: Fuel type
        fuel_clean = str(fuel).strip().capitalize()
        if fuel_clean not in SUPPORTED_FUELS:
            raise ValueError(
                f"Unsupported fuel '{fuel}'. Must be one of: {sorted(list(SUPPORTED_FUELS))}"
            )

        # 3. Validation: Physical positivity constraints
        if ambient_pressure_kpa <= 0.0:
            raise ValueError("Ambient pressure must be positive (> 0.0 kPa).")
        if droplet_initial_diameter_mm <= 0.0:
            raise ValueError("Initial droplet diameter must be positive (> 0.0 mm).")

        # 4. Validation: Gas mole fractions
        fractions = [o2_mole_fraction, n2_mole_fraction, co2_mole_fraction, he_mole_fraction]
        if any(f < 0.0 or f > 1.0 for f in fractions):
            raise ValueError("All gas mole fractions must be within [0.0, 1.0].")

        mole_sum = sum(fractions)
        warnings: List[str] = []
        if abs(mole_sum - 1.0) > 0.05:
            warnings.append(
                f"Gas mole fractions sum to {mole_sum:.3f}, deviating by >5% from conservation."
            )

        # 5. Out-of-Distribution / Extrapolation Checks
        bounds = self._metadata.get("feature_bounds", {}) if self._metadata else {}
        is_extrapolation = False

        if "ambient_pressure_kpa" in bounds:
            p_min, p_max = bounds["ambient_pressure_kpa"]["min"], bounds["ambient_pressure_kpa"]["max"]
            if ambient_pressure_kpa < p_min or ambient_pressure_kpa > p_max:
                is_extrapolation = True
                warnings.append(
                    f"Pressure {ambient_pressure_kpa:.1f} kPa is outside historical training range [{p_min:.1f}, {p_max:.1f} kPa]."
                )

        if "o2_mole_fraction" in bounds:
            o2_min, o2_max = bounds["o2_mole_fraction"]["min"], bounds["o2_mole_fraction"]["max"]
            if o2_mole_fraction < o2_min or o2_mole_fraction > o2_max:
                is_extrapolation = True
                warnings.append(
                    f"Oxygen mole fraction {o2_mole_fraction:.3f} is outside historical training range [{o2_min:.3f}, {o2_max:.3f}]."
                )

        if "droplet_initial_diameter_mm" in bounds:
            d_min, d_max = bounds["droplet_initial_diameter_mm"]["min"], bounds["droplet_initial_diameter_mm"]["max"]
            if droplet_initial_diameter_mm < d_min or droplet_initial_diameter_mm > d_max:
                is_extrapolation = True
                warnings.append(
                    f"Initial diameter {droplet_initial_diameter_mm:.2f} mm is outside historical training range [{d_min:.2f}, {d_max:.2f} mm]."
                )

        # 6. Select pipeline
        norm_choice = model_choice.lower().strip()
        if norm_choice in ["rf", "random_forest"] and self._rf_pipeline is not None:
            pipeline = self._rf_pipeline
            model_name = "Random Forest Regressor (max_depth=6)"
            selection_basis = (
                "Selected by user override. In cross-validation on training data, Random Forest achieved "
                "CV R² = 0.6873 ± 0.0449 and Grouped Date CV R² = 0.6371 ± 0.1755."
            )
        else:
            if self._ridge_pipeline is not None:
                pipeline = self._ridge_pipeline
                model_name = "Ridge Regression (Tuned)"
            else:
                pipeline = self._rf_pipeline
                model_name = "Random Forest Regressor"
            selection_basis = (
                "Selected as default deployed model based on training cross-validation evidence: "
                "Ridge Regression achieved higher CV R² (0.7321 ± 0.0657 vs RF 0.6873) and higher stability "
                "under Grouped Date CV (R² = 0.7437 vs RF 0.6371)."
            )

        # 7. Execute Inference
        input_df = pd.DataFrame([{
            "fuel": fuel_clean,
            "ambient_pressure_kpa": float(ambient_pressure_kpa),
            "o2_mole_fraction": float(o2_mole_fraction),
            "n2_mole_fraction": float(n2_mole_fraction),
            "co2_mole_fraction": float(co2_mole_fraction),
            "he_mole_fraction": float(he_mole_fraction),
            "droplet_initial_diameter_mm": float(droplet_initial_diameter_mm),
        }])

        pred_val = float(pipeline.predict(input_df)[0])
        pred_clamped = max(0.01, round(pred_val, 4))

        # Scientific Notes
        if fuel_clean == "Methanol":
            notes = (
                "Methanol burns with clean, soot-free blue diffusion flames. Combustion adheres closely to the "
                "classical d²-law with low radiative heat loss."
            )
        else:
            notes = (
                "Heptane produces dense soot agglomerations that remain trapped around the droplet in microgravity, "
                "inducing variable radiative heat loss and potential droplet micro-explosions."
            )

        return {
            "predicted_burning_rate_constant": pred_clamped,
            "units": "mm2/s",
            "model_name": model_name,
            "model_version": "1.0.0-flex",
            "model_selection_basis": selection_basis,
            "input_parameters": {
                "fuel": fuel_clean,
                "ambient_pressure_kpa": ambient_pressure_kpa,
                "o2_mole_fraction": o2_mole_fraction,
                "n2_mole_fraction": n2_mole_fraction,
                "co2_mole_fraction": co2_mole_fraction,
                "he_mole_fraction": he_mole_fraction,
                "droplet_initial_diameter_mm": droplet_initial_diameter_mm,
            },
            "is_extrapolation": is_extrapolation,
            "extrapolation_warnings": warnings,
            "scientific_disclaimer": SCIENTIFIC_DISCLAIMER,
            "scientific_notes": notes,
            "scientific_reliability": notes,
            "physical_domain": "NASA PSI-69 Quiescent Microgravity Droplet Combustion",
        }


# Singleton service instance
prediction_service = FlexPredictionService()


def predict_droplet_burning_rate(
    fuel: str,
    ambient_pressure_kpa: float,
    o2_mole_fraction: float,
    n2_mole_fraction: float,
    co2_mole_fraction: float,
    he_mole_fraction: float,
    droplet_initial_diameter_mm: float,
    model_choice: str = "ridge",
) -> Dict[str, Any]:
    """Convenience functional wrapper around prediction_service.predict."""
    return prediction_service.predict(
        fuel=fuel,
        ambient_pressure_kpa=ambient_pressure_kpa,
        o2_mole_fraction=o2_mole_fraction,
        n2_mole_fraction=n2_mole_fraction,
        co2_mole_fraction=co2_mole_fraction,
        he_mole_fraction=he_mole_fraction,
        droplet_initial_diameter_mm=droplet_initial_diameter_mm,
        model_choice=model_choice,
    )

